@passport_bp.route("/upload", methods=["POST"])
def upload_photo():

    if "photo" not in request.files:
        return error_response("No photo was selected.")

    photo = request.files["photo"]

    if not photo or not photo.filename:
        return error_response("Please select a photo.")

    original_name = photo.filename

    extension = Path(original_name).suffix.lower().lstrip(".")

    if extension not in current_app.config["ALLOWED_EXTENSIONS"]:
        return error_response(
            "Only JPG, JPEG, PNG and WEBP images are allowed."
        )

    unique_name = f"{uuid4().hex}.{extension}"

    upload_folder = get_upload_folder()
    upload_path = upload_folder / unique_name

    try:
        photo.save(upload_path)

        validate_image(upload_path)

        return jsonify({
            "success": True,
            "message": "Photo uploaded successfully.",
            "filename": unique_name,
            "original_name": original_name[:150]
        }), 200

    except ValueError as error:
        upload_path.unlink(missing_ok=True)
        return error_response(str(error))

    except Exception:
        upload_path.unlink(missing_ok=True)

        current_app.logger.exception("Photo upload failed.")

        return error_response(
            "Unable to upload this photo. Please try again.",
            500
        )


@passport_bp.route("/photo-preview/<filename>")
def photo_preview(filename):

    try:
        image_path = get_safe_upload_path(filename)

        if not image_path.is_file():
            return error_response("Photo not found.", 404)

        validate_image(image_path)

        return send_protected_file(
    image_path,
    mimetype={
        ".jpg": "image/jpeg",
        ".jpeg": "image/jpeg",
        ".png": "image/png",
        ".webp": "image/webp"
    }[image_path.suffix.lower()],
    conditional=True
)

    except ValueError:
        return error_response("Invalid photo filename.", 400)


@passport_bp.route("/change-background", methods=["POST"])
def change_photo_background():

    transparent_path = None
    final_path = None

    try:
        data = request.get_json(silent=True) or {}

        filename = data.get("filename")

        background_color = str(
            data.get("background_color", "")
        ).lower()

        input_path = get_safe_upload_path(filename)

        if background_color not in ALLOWED_BACKGROUND_COLORS:
            raise ValueError(
                "Please select White, Blue or Red background."
            )

        if not input_path.is_file():
            raise FileNotFoundError(
                "The selected photo was not found."
            )

        output_folder = get_output_folder()

        transparent_path = (
            output_folder / f"removed-{uuid4().hex}.png"
        )

        final_path = (
            get_upload_folder() / f"{uuid4().hex}.jpg"
        )

        with protect_file(input_path):

            validate_image(input_path)

            remove_background(
                input_path,
                transparent_path
            )

            change_background(
                transparent_path,
                final_path,
                background_color
            )

            validate_image(final_path)

        return jsonify({
            "success": True,
            "message": "Photo background changed successfully.",
            "filename": final_path.name,
            "background_color": background_color
        }), 200

    except (ValueError, FileNotFoundError) as error:
        if final_path:
            final_path.unlink(missing_ok=True)

        return error_response(str(error))

    except Exception:
        if final_path:
            final_path.unlink(missing_ok=True)

        current_app.logger.exception(
            "Photo background editing failed."
        )

        return error_response(
            "Unable to change the photo background. Please try again.",
            500
        )

    finally:
        if transparent_path:
            transparent_path.unlink(missing_ok=True)


@passport_bp.route("/generate-pdf", methods=["POST"])
def generate_pdf():

    started_at = time.monotonic()
    output_path = None

    current_app.logger.info(
        "[PDF DEBUG] 1. Request received."
    )

    try:
        data = request.get_json(silent=True) or {}

        photos = data.get("photos")

        max_photos = current_app.config["MAX_PHOTOS_PER_UPLOAD"]
        max_copies = current_app.config["MAX_COPIES_PER_PHOTO"]
        max_total = current_app.config["MAX_TOTAL_PDF_COPIES"]

        if not isinstance(photos, list) or not photos:
            raise ValueError("Please upload at least one photo.")

        if len(photos) > max_photos:
            raise ValueError(
                f"You can use a maximum of {max_photos} photos."
            )

        current_app.logger.info(
            "[PDF DEBUG] 2. Received %s photos.",
            len(photos)
        )

        try:
            photo_width_mm = float(data.get("photo_width_mm", 30))
            photo_height_mm = float(data.get("photo_height_mm", 40))
        except (TypeError, ValueError):
            raise ValueError("Please enter valid photo dimensions.")

        if not all(map(math.isfinite, [
            photo_width_mm,
            photo_height_mm
        ])):
            raise ValueError("Photo dimensions must be valid numbers.")

        if not (10 <= photo_width_mm <= 100):
            raise ValueError(
                "Photo width must be between 10 and 100 mm."
            )

        if not (10 <= photo_height_mm <= 100):
            raise ValueError(
                "Photo height must be between 10 and 100 mm."
            )

        photo_items = []
        total_copies = 0

        for item in photos:

            if not isinstance(item, dict):
                raise ValueError("Invalid photo information.")

            filename = item.get("filename")
            image_path = get_safe_upload_path(filename)

            copies_value = item.get("copies", 1)

            if isinstance(copies_value, bool):
                raise ValueError(
                    "Please enter a valid number of copies."
                )

            try:
                copies = int(copies_value)
            except (TypeError, ValueError):
                raise ValueError(
                    "Please enter a valid number of copies."
                )

            if str(copies_value).strip() != str(copies):
                raise ValueError(
                    "Please enter a whole number of copies."
                )

            if copies < 1 or copies > max_copies:
                raise ValueError(
                    f"Copies must be between 1 and {max_copies}."
                )

            total_copies += copies

            if total_copies > max_total:
                raise ValueError(
                    f"A PDF can contain a maximum of {max_total} photos."
                )

            if not image_path.is_file():
                raise FileNotFoundError(
                    "One of the uploaded photos could not be found."
                )

            current_app.logger.info(
                "[PDF DEBUG] Photo validated for request: %s | Size: %s bytes",
                image_path.name,
                image_path.stat().st_size
            )

            photo_items.append({
                "path": str(image_path),
                "copies": copies
            })

        output_filename = f"passport-{uuid4().hex}.pdf"
        output_path = get_output_folder() / output_filename

        unique_photo_paths = sorted({
            item["path"]
            for item in photo_items
        })

        current_app.logger.info(
            "[PDF DEBUG] 3. Waiting to acquire %s file lock(s).",
            len(unique_photo_paths)
        )

        with ExitStack() as stack:

            for photo_path in unique_photo_paths:

                current_app.logger.info(
                    "[PDF DEBUG] Waiting for lock: %s",
                    Path(photo_path).name
                )

                stack.enter_context(
                    protect_file(photo_path)
                )

                current_app.logger.info(
                    "[PDF DEBUG] Lock acquired: %s",
                    Path(photo_path).name
                )

            current_app.logger.info(
                "[PDF DEBUG] 4. All locks acquired. Validating images."
            )

            for item in photo_items:
                validate_image(item["path"])

            current_app.logger.info(
                "[PDF DEBUG] 5. Starting PDF generator."
            )

            generate_passport_pdf(
                photo_items=photo_items,
                output_path=output_path,
                photo_width_mm=photo_width_mm,
                photo_height_mm=photo_height_mm
            )

            current_app.logger.info(
                "[PDF DEBUG] 6. PDF generator completed in %.2f seconds.",
                time.monotonic() - started_at
            )

        current_app.logger.info(
            "[PDF DEBUG] 7. Sending PDF response."
        )

        response = send_protected_file(
            output_path,
            mimetype="application/pdf",
            as_attachment=True,
            download_name="ST-Passport-Photos.pdf"
        )

        current_app.logger.info(
            "[PDF DEBUG] 8. PDF response prepared in %.2f seconds.",
            time.monotonic() - started_at
        )

        return response

    except (ValueError, FileNotFoundError) as error:

        current_app.logger.warning(
            "[PDF DEBUG] Validation error: %s",
            str(error)
        )

        if output_path:
            output_path.unlink(missing_ok=True)

        return error_response(str(error))

    except Exception:

        current_app.logger.exception(
            "[PDF DEBUG] Passport PDF generation failed."
        )

        if output_path:
            output_path.unlink(missing_ok=True)

        return error_response(
            "Unable to generate the PDF. Please try again.",
            500
        )