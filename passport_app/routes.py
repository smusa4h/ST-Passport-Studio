ALLOWED_BACKGROUND_COLORS = {"white", "blue", "red"}


GENERATED_FILENAME_PATTERN = re.compile(
    r"^[a-f0-9]{32}\.(jpg|jpeg|png|webp)$"
)


def error_response(message, status_code=400):
    return jsonify({
        "success": False,
        "message": message
    }), status_code


def send_protected_file(file_path, **kwargs):
    """
    Read the file safely while its locks are active.
    Release the locks immediately after reading,
    then send the file to the browser from memory.
    """

    file_path = Path(file_path)

    current_app.logger.info(
        "[SEND LOCK DEBUG] Reading protected file: %s",
        file_path
    )

    # Acquire protection, read the file, then release protection.
    with protect_file(file_path):
        if not file_path.exists():
            raise FileNotFoundError(
                f"File not found: {file_path}"
            )

        file_data = file_path.read_bytes()

    current_app.logger.info(
        "[SEND LOCK DEBUG] File read successfully; locks released: %s",
        file_path
    )

    # BytesIO does not need file-based conditional handling.
    kwargs.pop("conditional", None)

    # Send the file from memory without keeping its lock occupied.
    return send_file(
        BytesIO(file_data),
        **kwargs
    )

def get_upload_folder():
    return Path(
        current_app.config["UPLOAD_FOLDER"]
    ).resolve()


def get_output_folder():
    return Path(
        current_app.config["OUTPUT_FOLDER"]
    ).resolve()


def get_safe_upload_path(filename):
    """Accept only filenames generated by this application."""

    if not isinstance(filename, str):
        raise ValueError("Invalid photo filename.")

    if not GENERATED_FILENAME_PATTERN.fullmatch(filename):
        raise ValueError("Invalid photo filename.")

    folder = get_upload_folder()
    path = (folder / filename).resolve()

    if path.parent != folder:
        raise ValueError("Invalid photo location.")

    return path


def validate_image(image_path):
    """Validate image format, integrity and dimensions."""

    allowed_formats = current_app.config["ALLOWED_IMAGE_FORMATS"]
    max_width = current_app.config["MAX_IMAGE_WIDTH"]
    max_height = current_app.config["MAX_IMAGE_HEIGHT"]

    try:
        with Image.open(image_path) as image:

            if image.format not in allowed_formats:
                raise ValueError("Unsupported image format.")

            width, height = image.size

            if width < 1 or height < 1:
                raise ValueError("Invalid image dimensions.")

            if width > max_width or height > max_height:
                raise ValueError(
                    "Image dimensions must not exceed 6000 × 6000 pixels."
                )

            image.verify()

        with Image.open(image_path) as image:
            image.load()

    except (
        UnidentifiedImageError,
        OSError,
        Image.DecompressionBombError
    ):
        raise ValueError(
            "The selected file is damaged or is not a valid image."
        )


